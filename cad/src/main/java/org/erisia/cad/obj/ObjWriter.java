package org.erisia.cad.obj;

import org.erisia.cad.Face;
import org.erisia.cad.Model;
import org.erisia.cad.Solid;
import org.erisia.cad.tex.Atlas;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.TreeSet;

/**
 * The OBJ targets (tools/models/README.md has the conventions), from models authored in px (0..16 a block, y up,
 * corner origin), each solid's material a palette name:
 * <ul>
 * <li>{@link #block}: NeoForge's neoforge:obj block model: coordinates 0..1, one usemtl group per material, MTL
 * map_Kd #material (the model JSON binds sprites), planar UVs at vanilla density (use "flip_v": true);</li>
 * <li>{@link #eln}: EA's Obj3D node model: centred (-0.5..0.5, floor at -0.5, front XN), triangles only, parts
 * (o NAME, each with its own usemtl), one atlas (16 px cells per material, UVs inset 0.3 texel from the cell
 * borders, V up: Obj3D flips it).</li>
 * </ul>
 * Polygons are fan-triangulated from their first corner (they are convex). Not byte-identical with mcmodel.py's
 * output; the geometry is the same.
 */
public final class ObjWriter {
    private ObjWriter() {
    }

    static String num(double v) {
        double r = Math.round(v * 1e6) / 1e6;
        if (r == 0) r = 0;
        String s = String.format(Locale.ROOT, "%.6f", r);
        s = s.replaceAll("0+$", "");
        return s.endsWith(".") ? s + "0" : s;
    }

    static final class Table {
        final Map<String, Integer> index = new HashMap<>();
        final List<String> lines = new ArrayList<>();

        int ref(String key, String line) {
            Integer i = index.get(key);
            if (i != null) return i;
            lines.add(line);
            index.put(key, lines.size());
            return lines.size();
        }
    }

    /** A neoforge:obj block model: NAME.obj and NAME.mtl in dir. Returns the triangle count. */
    public static int block(Model m, Path dir, String name) throws IOException {
        Table v = new Table(), vt = new Table(), vn = new Table();
        List<String> body = new ArrayList<>();
        List<Face> faces = m.faces();
        TreeSet<String> mats = new TreeSet<>();
        for (Face f : faces) mats.add(String.valueOf(f.solid.material));
        int tris = 0;
        for (String mat : mats) {
            body.add("usemtl " + mat);
            for (Face f : faces) {
                if (!mat.equals(String.valueOf(f.solid.material)) || f.nx == 0 && f.ny == 0 && f.nz == 0) continue;
                double[] uv = PlanarUv.of(f.xyz, f.n, f.nx, f.ny, f.nz);
                String n = num(Math.round(f.nx * 1e5) / 1e5) + " " + num(Math.round(f.ny * 1e5) / 1e5) + " " + num(Math.round(f.nz * 1e5) / 1e5);
                int ni = vn.ref(n, "vn " + n);
                String[] ids = new String[f.n];
                for (int i = 0; i < f.n; i++) {
                    String p = num(f.xyz[3 * i] / 16) + " " + num(f.xyz[3 * i + 1] / 16) + " " + num(f.xyz[3 * i + 2] / 16);
                    String t = num(uv[2 * i]) + " " + num(uv[2 * i + 1]);
                    ids[i] = v.ref(p, "v " + p) + "/" + vt.ref(t, "vt " + t) + "/" + ni;
                }
                for (int k = 1; k + 1 < f.n; k++) {
                    body.add("f " + ids[0] + " " + ids[k] + " " + ids[k + 1]);
                    tris++;
                }
            }
        }
        List<String> out = new ArrayList<>(List.of("# generated by org.erisia.cad (neoforge:obj block model)", "mtllib " + name + ".mtl", "o main"));
        out.addAll(v.lines);
        out.addAll(vt.lines);
        out.addAll(vn.lines);
        out.addAll(body);
        Files.writeString(dir.resolve(name + ".obj"), String.join("\n", out) + "\n");
        StringBuilder mtl = new StringBuilder();
        for (String mat : mats) mtl.append("newmtl ").append(mat).append("\nKa 0 0 0\nKd 1 1 1\nd 1\nmap_Kd #").append(mat).append("\n\n");
        Files.writeString(dir.resolve(name + ".mtl"), mtl.toString());
        return tris;
    }

    /** One part of an EA node model: its name and solids (px, this model's frame). */
    public record EPart(String name, List<Solid> solids) {
    }

    /**
     * An EA Obj3D node model: NAME.obj and NAME.mtl (map_Kd TEX) in dir, every solid's material a cell of the atlas.
     * Returns the triangle count. The atlas image is the caller's (Atlas.paint, written as TEX).
     */
    public static int eln(List<EPart> parts, Atlas atlas, Path dir, String name, String tex) throws IOException {
        double inset = 0.3 / 16;
        Table v = new Table(), vt = new Table();
        List<List<String>> groups = new ArrayList<>();
        int tris = 0;
        for (EPart part : parts) {
            List<String> out = new ArrayList<>();
            for (Solid s : part.solids()) {
                if (s.ghost) continue;
                int[] cell = atlas.cells.get(String.valueOf(s.material));
                if (cell == null) throw new IllegalArgumentException(s + ": no atlas cell for " + s.material);
                for (Face f : s.faces()) {
                    if (f.nx == 0 && f.ny == 0 && f.nz == 0) continue;
                    double[] uv = PlanarUv.of(f.xyz, f.n, f.nx, f.ny, f.nz);
                    String[] ids = new String[f.n];
                    for (int i = 0; i < f.n; i++) {
                        double u = inset + uv[2 * i] * (1 - 2 * inset), w = inset + uv[2 * i + 1] * (1 - 2 * inset);
                        String t = num((cell[0] + u) / atlas.cols) + " " + num((atlas.rows - 1 - cell[1] + w) / atlas.rows);
                        String p = num(f.xyz[3 * i] / 16 - 0.5) + " " + num(f.xyz[3 * i + 1] / 16 - 0.5) + " " + num(f.xyz[3 * i + 2] / 16 - 0.5);
                        ids[i] = v.ref(p, "v " + p) + "/" + vt.ref(t, "vt " + t);
                    }
                    for (int k = 1; k + 1 < f.n; k++) {
                        out.add("f " + ids[0] + " " + ids[k] + " " + ids[k + 1]);
                        tris++;
                    }
                }
            }
            groups.add(out);
        }
        // (Obj3D needs a part open before the first vertex; the vertex list is shared by the parts)
        List<String> lines = new ArrayList<>(List.of("# generated by org.erisia.cad (EA Obj3D format)", "mtllib " + name + ".mtl", "o " + parts.get(0).name()));
        lines.addAll(v.lines);
        lines.addAll(vt.lines);
        for (int k = 0; k < parts.size(); k++) {
            if (k > 0) lines.add("o " + parts.get(k).name());
            lines.add("usemtl atlas");
            lines.addAll(groups.get(k));
        }
        Files.writeString(dir.resolve(name + ".obj"), String.join("\n", lines) + "\n");
        Files.writeString(dir.resolve(name + ".mtl"), "newmtl atlas\nKa 0 0 0\nKd 1 1 1\nd 1\nmap_Kd " + tex + "\n");
        return tris;
    }
}
