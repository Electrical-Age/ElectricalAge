def _tokens(s):
    """Split 'A{GE}1' into ['A', 'GE', '1']."""
    out, i = [], 0
    while i < len(s):
        if s[i] == '{':
            j = s.index('}', i)
            out.append(s[i + 1:j]); i = j + 1
        else:
            out.append(s[i].upper() if s[i].isalpha() else s[i]); i += 1
    return out


def glyph_rows(tok, font=FONT5):
    """Rows of one glyph (a character or a symbol name).  KeyError lists what exists."""
    try:
        return font[tok]
    except KeyError:
        raise KeyError(f'glyph {tok!r} not in font; have: {" ".join(sorted(font))}') from None


def squash(rows, height):
    """Shorten a glyph to ``height`` rows by dropping rows that repeat the row above them
    (straight stems), bottom-most first.  Used to fit an overbar into the 16 px chip cell.
    Returns the rows unchanged if the glyph has too few repeated rows."""
    rows = list(rows)
    i = len(rows) - 1
    while len(rows) > height and i > 0:
        if rows[i] == rows[i - 1]:
            del rows[i]
        i -= 1
    return rows


def text_size(s, font=FONT5, gap=1, scale=1):
    """(width, height) in px of a string drawn with ``text``."""
    toks = _tokens(s)
    if not toks:
        return 0, 0
    w = sum(len(glyph_rows(t, font)[0]) for t in toks) + gap * (len(toks) - 1)
    hgt = max(len(glyph_rows(t, font)) for t in toks)
    return w * scale, hgt * scale


def text(cv, x, y, s, colour, font=FONT5, gap=1, scale=1, colours=None, overbar=False):
    """Draw string ``s`` with its top-left at (x, y); return its width.

    ``colours``: optional list, one colour per glyph token (e.g. J blue, K green).
    ``overbar``: a bar over the whole string, one empty row above it (row y-2*scale);
    pass ``True`` or a colour.  Glyphs shorter than the tallest are bottom-aligned.
    """
    toks = _tokens(s)
    _, hgt = text_size(s, font, gap, 1)
    cx = x
    for i, t in enumerate(toks):
        rows = glyph_rows(t, font)
        c = colours[i] if colours else colour
        oy = y + (hgt - len(rows)) * scale
        for ry, row in enumerate(rows):
            for rx, ch in enumerate(row):
                if ch == '#':
                    for dy in range(scale):
                        for dx in range(scale):
                            cv.set(cx + rx * scale + dx, oy + ry * scale + dy, c)
        cx += (len(rows[0]) + gap) * scale
    w = cx - x - gap * scale
    if overbar:
        oc = colour if overbar is True else overbar
        for dy in range(scale):
            cv.hline(x, x + w - 1, y - 2 * scale + dy, oc)
    return w
