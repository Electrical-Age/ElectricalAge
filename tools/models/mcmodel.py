#!/usr/bin/env python3
"""mcmodel: a tiny code-CAD for Minecraft baked OBJ models (NeoForge "neoforge:obj" loader).

Units are Minecraft pixels (16 per block); the block spans 0..16 on each axis, Y up, corner origin
(the loader uses 0..1 block coordinates; we divide by 16 on output). Every primitive carries a
material name; the OBJ gets one `usemtl` group per material and the MTL maps each material to a
model texture variable (`map_Kd #name`), which the model JSON binds to an atlas sprite.

UVs: planar projection along the face's dominant normal axis, in block units, so textures land at
vanilla density (16 px per block); each face is shifted into 0..1 because atlas sprites can't wrap.
Use with "flip_v": true (standard OBJ V-up convention; verified in-game with a marker texture).

Primitives (all return a Mesh; combine with Model.add):
  box(x0,y0,z0, x1,y1,z1, mat)
  prism(axis, c1, c2, r, a0, a1, mat, n=12, r_end=None, caps=(True,True), phase=None)
      n-gon cylinder/frustum along axis 'x'|'y'|'z', centre (c1,c2) in the other two axes (in xyz order),
      from a0 to a1 along the axis, radius r (r_end for a frustum).
  tube(axis, c1, c2, r_in, r_out, a0, a1, mat, n=12)   annulus (fins, rings)
"""
import math

class Mesh:
    def __init__(self, mat):
        self.mat = mat
        self.quads = []          # list of polygons (3 or 4 vertices, CCW seen from outside)

    def poly(self, *vs):
        self.quads.append([tuple(map(float, v)) for v in vs])
        return self

class Model:
    def __init__(self):
        self.meshes = []

    def add(self, *meshes):
        self.meshes.extend(meshes)
        return self

    def triangles(self):
        return sum(len(p) - 2 for m in self.meshes for p in m.quads)

    def materials(self):
        return sorted({m.mat for m in self.meshes})

    def write_obj(self, path, mtl_name):
        vs, vts, vns, out = [], [], [], [f"# generated by mcmodel.py", f"mtllib {mtl_name}", "o main"]
        vidx, tidx, nidx = {}, {}, {}

        def ref(table, lst, key):
            if key not in table:
                lst.append(key)
                table[key] = len(lst)
            return table[key]

        for mat in self.materials():
            out.append(f"usemtl {mat}")
            for m in self.meshes:
                if m.mat != mat:
                    continue
                for p in m.quads:
                    n = normal(p)
                    if n is None:
                        continue
                    uv = planar_uv(p, n)
                    ni = ref(nidx, vns, tuple(round(c, 5) for c in n))
                    ids = []
                    for v, t in zip(p, uv):
                        vi = ref(vidx, vs, tuple(round(c / 16.0, 6) for c in v))
                        ti = ref(tidx, vts, (round(t[0], 6), round(t[1], 6)))
                        ids.append(f"{vi}/{ti}/{ni}")
                    for k in range(1, len(ids) - 1):        # fan-triangulate (convex polygons only)
                        out.append(f"f {ids[0]} {ids[k]} {ids[k + 1]}")
        head = [f"v {x} {y} {z}" for x, y, z in vs] + [f"vt {u} {v}" for u, v in vts] + [f"vn {a} {b} {c}" for a, b, c in vns]
        with open(path, "w") as f:
            f.write("\n".join(out[:3] + head + out[3:]) + "\n")

    def write_mtl(self, path):
        with open(path, "w") as f:
            for mat in self.materials():
                f.write(f"newmtl {mat}\nKa 0 0 0\nKd 1 1 1\nd 1\nmap_Kd #{mat}\n\n")

    def write_eln(self, outdir, name, cells, grid, tex="tex.png", part="main", inset=0.3 / 16):
        """EA 1.12 node model (Obj3D loader, drawn by a block-entity renderer): writes OUTDIR/NAME.obj + NAME.mtl.
        Coordinates are centred on the block (-0.5..0.5, floor at y = -0.5): px (0..16) -> px/16 - 0.5. Front = XN
        (x = 0 px) after the renderer's front.glRotateXnRef(). Triangles only (Obj3D drops other faces; normals come
        from the winding, back faces are culled). One part, one material, one texture: every material is a cell of
        an atlas TEX laid out as GRID = (cols, rows); CELLS maps material -> (col, row), row 0 = top of the image.
        Obj3D stores 1 - v, so V-up is written as usual. INSET (cell units) keeps samples off the cell borders."""
        import os
        cols, rows = grid
        vs, vts, out = [], [], []
        vidx, tidx = {}, {}

        def ref(table, lst, key):
            if key not in table:
                lst.append(key)
                table[key] = len(lst)
            return table[key]

        for m in self.meshes:
            col, row = cells[m.mat]
            for p in m.quads:
                n = normal(p)
                if n is None:
                    continue
                ids = []
                for v, (u, w) in zip(p, planar_uv(p, n)):
                    u = inset + u * (1 - 2 * inset)
                    w = inset + w * (1 - 2 * inset)
                    t = ((col + u) / cols, (rows - 1 - row + w) / rows)
                    vi = ref(vidx, vs, tuple(round(c / 16.0 - 0.5, 6) for c in v))
                    ti = ref(tidx, vts, (round(t[0], 6), round(t[1], 6)))
                    ids.append(f"{vi}/{ti}")
                for k in range(1, len(ids) - 1):
                    out.append(f"f {ids[0]} {ids[k]} {ids[k + 1]}")
        mtl = name + ".mtl"
        lines = ["# generated by mcmodel.py (EA Obj3D format)", f"mtllib {mtl}", f"o {part}"]
        lines += [f"v {x} {y} {z}" for x, y, z in vs] + [f"vt {u} {v}" for u, v in vts]
        lines += ["usemtl atlas"] + out
        with open(os.path.join(outdir, name + ".obj"), "w") as f:
            f.write("\n".join(lines) + "\n")
        with open(os.path.join(outdir, mtl), "w") as f:
            f.write(f"newmtl atlas\nKa 0 0 0\nKd 1 1 1\nd 1\nmap_Kd {tex}\n")
        return len(out)

def oriented(poly, hint):
    """Return POLY wound so its normal points along HINT (a rough outward direction)."""
    n = normal(poly)
    return poly if n is None or sum(a * b for a, b in zip(n, hint)) >= 0 else list(reversed(poly))

def sub(a, b): return (a[0] - b[0], a[1] - b[1], a[2] - b[2])
def cross(a, b): return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])

def normal(p):
    n = (0.0, 0.0, 0.0)
    for i in range(1, len(p) - 1):     # sum of fan cross products (robust for quads)
        c = cross(sub(p[i], p[0]), sub(p[i + 1], p[0]))
        n = (n[0] + c[0], n[1] + c[1], n[2] + c[2])
    l = math.sqrt(sum(c * c for c in n))
    return None if l < 1e-9 else (n[0] / l, n[1] / l, n[2] / l)

def planar_uv(p, n):
    """Project onto the plane of the dominant axis; u/v chosen so the texture is upright on side faces
    and north-up on top/bottom faces, like vanilla. Block units, shifted into 0..1."""
    ax = max(range(3), key=lambda i: abs(n[i]))
    s = 1 / 16.0
    if ax == 1:      # top/bottom: u = x, v = -z (north at the top of the texture)
        uv = [(v[0] * s, -v[2] * s) for v in p]
        if n[1] < 0: uv = [(u, -w) for u, w in uv]
    elif ax == 0:    # east/west faces: u along z (mirrored per side so it reads left-to-right), v = y
        uv = [((-v[2] if n[0] > 0 else v[2]) * s, v[1] * s) for v in p]
    else:            # north/south faces: u along x, v = y
        uv = [((v[0] if n[2] > 0 else -v[0]) * s, v[1] * s) for v in p]
    u0 = math.floor(min(u for u, _ in uv) + 1e-6)
    v0 = math.floor(min(w for _, w in uv) + 1e-6)
    uv = [(u - u0, w - v0) for u, w in uv]
    if max(max(u, w) for u, w in uv) > 1 + 1e-6:     # wider than a sprite: squeeze (shouldn't happen inside a block)
        k = max(max(u, w) for u, w in uv)
        uv = [(u / k, w / k) for u, w in uv]
    return uv

def box(x0, y0, z0, x1, y1, z1, mat, faces="nsewud"):
    m = Mesh(mat)
    if "u" in faces: m.poly((x0, y1, z0), (x0, y1, z1), (x1, y1, z1), (x1, y1, z0))
    if "d" in faces: m.poly((x0, y0, z0), (x1, y0, z0), (x1, y0, z1), (x0, y0, z1))
    if "s" in faces: m.poly((x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1))
    if "n" in faces: m.poly((x1, y0, z0), (x0, y0, z0), (x0, y1, z0), (x1, y1, z0))
    if "e" in faces: m.poly((x1, y0, z1), (x1, y0, z0), (x1, y1, z0), (x1, y1, z1))
    if "w" in faces: m.poly((x0, y0, z0), (x0, y0, z1), (x0, y1, z1), (x0, y1, z0))
    return m

def _frame(axis):
    """Map (a, c1, c2) -> (x, y, z) for an axis; c1, c2 are the other two axes in xyz order.
    Also return whether (c1, c2, a) is a right-handed frame (to keep CCW winding)."""
    if axis == "x": return (lambda a, p, q: (a, p, q)), True     # (y, z, x): y x z = x
    if axis == "y": return (lambda a, p, q: (p, a, q)), False    # (x, z, y): x x z = -y
    return (lambda a, p, q: (p, q, a)), True                     # (x, y, z)

def prism(axis, c1, c2, r, a0, a1, mat, n=12, r_end=None, caps=(True, True), phase=None):
    """n-gon cylinder (or frustum when r_end is given) along axis from a0 to a1 (a0 < a1)."""
    f, rh = _frame(axis)
    r_end = r if r_end is None else r_end
    ph = (math.pi / n) if phase is None else phase       # flat side up by default
    ring = lambda a, rr: [f(a, c1 + rr * math.cos(ph + 2 * math.pi * i / n), c2 + rr * math.sin(ph + 2 * math.pi * i / n)) for i in range(n)]
    lo, hi = ring(a0, r), ring(a1, r_end)
    m = Mesh(mat)
    for i in range(n):
        j = (i + 1) % n
        q = [lo[i], lo[j], hi[j], hi[i]] if rh else [lo[j], lo[i], hi[i], hi[j]]
        m.poly(*q)
    if caps[0] and r > 0:
        m.poly(*(list(reversed(lo)) if rh else lo))
    if caps[1] and r_end > 0:
        m.poly(*(hi if rh else list(reversed(hi))))
    return m

def tube(axis, c1, c2, r_in, r_out, a0, a1, mat, n=12, phase=None, inner=True):
    """Annulus: outer wall, inner wall (skip with inner=False when it sits on a body), flat ring ends."""
    f, rh = _frame(axis)
    ph = (math.pi / n) if phase is None else phase
    ring = lambda a, rr: [f(a, c1 + rr * math.cos(ph + 2 * math.pi * i / n), c2 + rr * math.sin(ph + 2 * math.pi * i / n)) for i in range(n)]
    o0, o1, i0, i1 = ring(a0, r_out), ring(a1, r_out), ring(a0, r_in), ring(a1, r_in)
    m = Mesh(mat)
    for i in range(n):
        j = (i + 1) % n
        if rh:
            m.poly(o0[i], o0[j], o1[j], o1[i])
            if inner: m.poly(i0[j], i0[i], i1[i], i1[j])
            m.poly(o0[j], o0[i], i0[i], i0[j]); m.poly(o1[i], o1[j], i1[j], i1[i])
        else:
            m.poly(o0[j], o0[i], o1[i], o1[j])
            if inner: m.poly(i0[i], i0[j], i1[j], i1[i])
            m.poly(o0[i], o0[j], i0[j], i0[i]); m.poly(o1[j], o1[i], i1[i], i1[j])
    return m

def volute(axis, c1, c2, r0, r1, a0, a1, mat, n=20, start=0.0):
    """Scroll (spiral) casing along AXIS: the radius grows linearly from r0 to r1 over one turn starting at angle
    START (radians, 0 = +c1, pi/2 = +c2), closed by a radial 'tongue' wall where it steps back to r0. The caps are
    fanned from the centre (the outline is star-shaped, not convex)."""
    f, _ = _frame(axis)
    ai = "xyz".index(axis)
    unit = lambda i: tuple(1.0 if k == i else 0.0 for k in range(3))
    def pt(a, ang, rr): return f(a, c1 + rr * math.cos(ang), c2 + rr * math.sin(ang))
    def radial(ang): return f(0, math.cos(ang), math.sin(ang))
    angs = [start + 2 * math.pi * k / n for k in range(n + 1)]
    rad = [r0 + (r1 - r0) * k / n for k in range(n + 1)]
    m = Mesh(mat)
    for k in range(n):
        q = [pt(a0, angs[k], rad[k]), pt(a0, angs[k + 1], rad[k + 1]), pt(a1, angs[k + 1], rad[k + 1]), pt(a1, angs[k], rad[k])]
        m.poly(*oriented(q, radial((angs[k] + angs[k + 1]) / 2)))
        for a, s in ((a0, -1), (a1, 1)):
            tri = [f(a, c1, c2), pt(a, angs[k], rad[k]), pt(a, angs[k + 1], rad[k + 1])]
            m.poly(*oriented(tri, tuple(s * c for c in unit(ai))))
    # tongue wall: faces the direction of increasing angle
    tang = f(0, -math.sin(start), math.cos(start))
    m.poly(*oriented([pt(a0, start, r0), pt(a0, start, r1), pt(a1, start, r1), pt(a1, start, r0)], tang))
    return m
