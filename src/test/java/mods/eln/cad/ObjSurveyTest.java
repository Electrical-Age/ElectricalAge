package mods.eln.cad;

import org.erisia.cad.Checker;
import org.erisia.cad.obj.ObjReader;
import org.junit.jupiter.api.Test;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.stream.Stream;

import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * The checker over every OBJ the mod ships (board #44): EA's node models (Obj3D) and the block models (neoforge:obj).
 * Reports, never fails (the 1.12 Blender models have many coplanar faces; the code-CAD ones are listed first);
 * -PcadReport=PREFIX writes the report. A polygon soup can't tell what is hidden inside another solid, so some reports
 * are faces nobody sees.
 */
public class ObjSurveyTest {
    @Test
    void everyObj() throws Exception {
        Path res = Path.of(System.getProperty("eln.resources", "src/main/resources"), "assets/eln");
        List<Path> objs = new ArrayList<>();
        for (String dir : new String[]{"model", "models/block"})
            try (Stream<Path> s = Files.walk(res.resolve(dir))) {
                s.filter(p -> p.toString().endsWith(".obj")).sorted().forEach(objs::add);
            }
        List<String> cad = new ArrayList<>(), old = new ArrayList<>();
        int clean = 0, read = 0;
        for (Path p : objs) {
            var m = ObjReader.read(p, !p.toString().contains("models/block"));
            read++;
            var issues = Checker.faces(m.faces());
            long fights = issues.stream().filter(i -> i.rule().equals("z-fight")).count(), degen = issues.size() - fights;
            if (issues.isEmpty() && m.problems().isEmpty()) {
                clean++;
                continue;
            }
            String line = res.relativize(p) + ": " + m.faces().size() + " faces, " + fights + " z-fighting pairs, " + degen + " degenerate"
                + (m.problems().isEmpty() ? "" : ", " + m.problems().size() + " unreadable faces");
            String first = issues.isEmpty() ? "" : "\n    e.g. " + issues.get(0).toString().replace("\n", "\n    ");
            (m.header().startsWith("generated by") ? cad : old).add(line + first);
        }
        StringBuilder b = new StringBuilder(read + " OBJs read, " + clean + " clean\n\nCode-CAD (tools/models: mcmodel.py, oilkit.py), " + cad.size() + " with findings:\n");
        for (String s : cad) b.append(s).append('\n');
        b.append("\n1.12 Blender models, ").append(old.size()).append(" with findings:\n");
        for (String s : old) b.append(s).append('\n');
        System.out.println(b);
        String out = System.getProperty("cad.report");
        if (out != null) Files.writeString(Path.of(out + "-obj.txt"), b.toString());
        assertTrue(read > 100, "the OBJs were found");
    }
}
